import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const envFile = process.argv[2] || ".env";
const envPath = resolve(root, envFile);
const outputPath = resolve(root, "config.js");

function parseEnv(text) {
    const values = {};

    for (const rawLine of text.split(/\r?\n/)) {
        const line = rawLine.trim();
        if (!line || line.startsWith("#")) continue;

        const separator = line.indexOf("=");
        if (separator < 1) continue;

        const key = line.slice(0, separator).trim();
        let value = line.slice(separator + 1).trim();

        const quoted =
            (value.startsWith('"') && value.endsWith('"')) ||
            (value.startsWith("'") && value.endsWith("'"));
        if (quoted) value = value.slice(1, -1);

        values[key] = value;
    }

    return values;
}

if (!existsSync(envPath)) {
    console.error(`Missing ${envPath}. Copy .env.example to .env and fill it in.`);
    process.exit(1);
}

const env = parseEnv(readFileSync(envPath, "utf8"));
const apiKey = (env.WEATHER_API_KEY || "").trim();
const proxyUrl = (env.WEATHER_PROXY_URL || "").trim();
const defaultCity = (env.WEATHER_DEFAULT_CITY || "").trim();

if (!apiKey && !proxyUrl) {
    console.error(`Set WEATHER_API_KEY or WEATHER_PROXY_URL in ${envPath}.`);
    process.exit(1);
}

const config = {
    apiKey: proxyUrl ? "" : apiKey,
    proxyUrl,
    defaultCity,
};

const banner = "// Generated by scripts/generate-config.mjs from .env. Do not edit or commit.\n";
writeFileSync(
    outputPath,
    banner + "window.WEATHER_CONFIG = " + JSON.stringify(config, null, 4) + ";\n",
    "utf8"
);

console.log(
    `Wrote config.js (${proxyUrl ? "proxy" : "direct"} mode, default city: ${defaultCity || "none"})`
);
